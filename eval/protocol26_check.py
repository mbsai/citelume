"""
Selection protocol 2.6 against 2.5 on the development reviews (eval/PROTOCOL.md, amendment of 26 Nov 2026).

    python -m eval.protocol26_check --v25 runs/26check_v25 --v26 runs/26check_v26

Both versions were run without a model (rule-based planning), the same day, alternating question by question, so the
difference reflects the protocol change plus the run-to-run variation of the sources (eval/results/7_findings.md,
E2c: identical repeats shared a median 63% of their records). Development reviews only; writes
eval/results/2.6_dev_check.md and .json.
"""
from __future__ import annotations

import argparse
import gzip
import json
from pathlib import Path
from statistics import mean, median

from eval.scoring import match, review_split

RESULTS = Path(__file__).resolve().parent / "results"


def load(run_dir: Path, rid: str):
    folder = run_dir / rid
    try:
        corpus = json.loads(gzip.decompress((folder / "corpus.json.gz").read_bytes()))
        run = json.loads((folder / "run.json").read_text())
    except (OSError, ValueError):
        return None
    return corpus, run


def found(included, records) -> int:
    return len(match(included, records).found)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="python -m eval.protocol26_check")
    p.add_argument("--v25", type=Path, required=True)
    p.add_argument("--v26", type=Path, required=True)
    a = p.parse_args(argv)
    rows = []
    for review in review_split("development"):
        rid, included = review["review_id"], review["included"]
        out = {"review": rid, "included": len(included)}
        for tag, folder in (("v25", a.v25), ("v26", a.v26)):
            got = load(folder, rid)
            if got is None:
                out[tag] = None
                continue
            corpus, run = got
            records = corpus.get("records", [])
            ids = set(corpus.get("included_ids") or [])
            selected = [r for r in records if r.get("id") in ids]
            concepts = [c.get("name") for c in ((corpus.get("protocol") or {}).get("concepts") or [])]
            out[tag] = {"version": corpus.get("protocol_version"), "records": len(records),
                        "pool": found(included, records), "eligible_selected": found(included, selected),
                        "concepts": concepts, "status": run.get("status")}
        rows.append(out)
    done = [r for r in rows if r["v25"] and r["v26"]]

    def share(r, tag, key):
        return r[tag][key] / r["included"] if r["included"] else 0.0

    summary = {
        "reviews": len(done),
        "pool_recall_mean": {t: round(mean(share(r, t, "pool") for r in done), 3) for t in ("v25", "v26")} if done else {},
        "pool_recall_median": {t: round(median(share(r, t, "pool") for r in done), 3) for t in ("v25", "v26")} if done else {},
        "selected_recall_mean": {t: round(mean(share(r, t, "eligible_selected") for r in done), 3) for t in ("v25", "v26")} if done else {},
        "concepts_changed": sum(1 for r in done if r["v25"]["concepts"] != r["v26"]["concepts"]),
    }
    RESULTS.joinpath("2.6_dev_check.json").write_text(json.dumps({"summary": summary, "rows": rows}, indent=1) + "\n")
    lines = ["# Selection protocol 2.6 against 2.5 (development reviews, no model)", "",
             "Generated by `python -m eval.protocol26_check`. Both versions planned by rules, run the same day, "
             "alternating question by question. Recall: share of each review's included studies (mean over reviews).",
             "", f"Reviews compared: {summary['reviews']} of 11. Concepts changed in {summary['concepts_changed']}.", "",
             "| | 2.5 | 2.6 |", "|---|---|---|"]
    if done:
        for label, key in (("Pool recall, mean", "pool_recall_mean"), ("Pool recall, median", "pool_recall_median"),
                           ("Selected (without model screening), mean", "selected_recall_mean")):
            lines.append(f"| {label} | {summary[key]['v25']:.0%} | {summary[key]['v26']:.0%} |")
    lines += ["", "| Review | Included | Records 2.5 / 2.6 | Pool 2.5 / 2.6 | Selected 2.5 / 2.6 | Concepts 2.5 -> 2.6 |",
              "|---|---|---|---|---|---|"]
    for r in rows:
        if not (r["v25"] and r["v26"]):
            lines.append(f"| {r['review']} | {r['included']} | run missing | | | |")
            continue
        c25, c26 = "; ".join(r["v25"]["concepts"]), "; ".join(r["v26"]["concepts"])
        lines.append(f"| {r['review']} | {r['included']} | {r['v25']['records']} / {r['v26']['records']} | "
                     f"{r['v25']['pool']} / {r['v26']['pool']} | {r['v25']['eligible_selected']} / "
                     f"{r['v26']['eligible_selected']} | {c25 if c25 == c26 else c25 + ' -> ' + c26} |")
    RESULTS.joinpath("2.6_dev_check.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
